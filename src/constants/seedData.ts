export function seedDemoData(options?: { force?: boolean }) {
  const alreadySeeded = localStorage.getItem(STORAGE_KEYS.seeded) === 'true'
  const existingModules = readStorage<Record<string, unknown[]>>(STORAGE_KEYS.moduleData, {})
  const isEmpty = Object.keys(existingModules).length === 0

  if (alreadySeeded && !options?.force && !isEmpty) {
    return { seeded: false, reason: 'already-seeded' as const }
  }

  writeStorage(STORAGE_KEYS.moduleData, demoModuleData)
  saveCompanySettings(demoCompany)
  writeStorage(STORAGE_KEYS.dashboardStats, demoDashboardStats)
  writeStorage(STORAGE_KEYS.revenueChart, demoRevenueChart)
  writeStorage(STORAGE_KEYS.progressChart, demoProgressChart)
  localStorage.setItem(STORAGE_KEYS.seeded, 'true')

  return { seeded: true, reason: 'ok' as const }
}

